"""Write content/media.js: the pixel size of every image and video poster under assets/.

Run after adding or replacing media:  python tools/media-manifest.py
The site works without it, but layouts settle instantly when sizes are known.
Needs Pillow (pip install pillow).
"""
import json
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent
sizes = {}
for p in sorted((root / "assets").rglob("*")):
    if p.suffix.lower() in {".webp", ".jpg", ".jpeg", ".png"}:
        with Image.open(p) as im:
            sizes[p.relative_to(root).as_posix()] = list(im.size)

out = root / "content" / "media.js"
out.write_text("/* Generated by tools/media-manifest.py — do not edit by hand. */\n"
               "window.MEDIA_SIZES = " + json.dumps(sizes, indent=0) + ";\n", encoding="utf-8")
print(f"{len(sizes)} images -> {out.relative_to(root)}")
